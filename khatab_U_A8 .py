# Week 8 Assignment - Classes & Inheritance
# This program builds directly on top of the Week 7 program structure.
# In Week 7 the data was stored in plain dictionaries and the validators
# were loose stand-alone functions. In this version everything is organized
# using classes, as required by the assignment:
